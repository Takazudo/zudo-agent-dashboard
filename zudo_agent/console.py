"""Opt-in human pane console. Never part of observation storage or forwarding.

The target is an existing pane, including its shell after a foreground job exits.
Only server-generated tmux commands reach a connection bound to that server.
"""
import base64
from contextlib import nullcontext
import hashlib
import hmac
import os
import re
import select
import secrets
import stat
import subprocess
import threading
import time
import unicodedata

from . import collector
